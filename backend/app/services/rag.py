"""Retrieval-augmented fact-check layer.

Pipeline: claim -> embedding -> FAISS nearest-neighbour search over a controlled knowledge base -> evidence ->
rule-based stance assessment (supported / contradicted / insufficient / unverified).

The knowledge base indexes two kinds of vectors per entry: the established *statement*, and each *known false
claim* phrasing. A claim that lands next to a false-claim vector (with matching polarity) is 'contradicted'; one
that lands next to the statement is 'supported'. Negation polarity is compared so "vaccines do NOT cause autism"
is not mistaken for the false claim.

Embedding backends:
  * tfidf (default): TF-IDF 1-2-gram vectors fitted on the KB, L2-normalised, held in a dense FAISS IndexFlatIP.
  * sentence-transformers (optional): `EMBEDDING_BACKEND=sentence-transformers` for semantic embeddings.
Evidence is retrieved from the curated KB only; nothing here is generated by a language model.
"""
from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass
from pathlib import Path

import faiss
import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer

from ..config import get_settings
from ..nlp.lexicons import NEGATION_CUES

log = logging.getLogger(__name__)

RELEVANT_MIN = 0.28  # below this a hit is considered unrelated
DECISIVE_MIN = 0.42  # at/above this a hit is considered a close match to the claim


@dataclass
class KBItem:
    entry_idx: int
    kind: str  # "statement" | "false_claim"
    text: str


def negation_polarity(text: str) -> int:
    """0 for affirmative, 1 for negated (odd number of negation cues)."""
    low = text.lower().replace("n't", " not")
    toks = re.findall(r"[a-z']+", low)
    return sum(1 for t in toks if t in NEGATION_CUES) % 2


class TfidfEmbedder:
    name = "tfidf"

    def __init__(self, corpus: list[str]):
        self.vec = TfidfVectorizer(ngram_range=(1, 2), stop_words="english", sublinear_tf=True, min_df=1, norm="l2")
        self.vec.fit(corpus)
        self.dim = len(self.vec.vocabulary_)

    def encode(self, texts: list[str]) -> np.ndarray:
        return self.vec.transform(texts).toarray().astype("float32")


class SentenceTransformerEmbedder:
    name = "sentence-transformers"

    def __init__(self, model_name: str):
        from sentence_transformers import SentenceTransformer  # optional dependency

        self.model = SentenceTransformer(model_name)
        self.dim = self.model.get_sentence_embedding_dimension()

    def encode(self, texts: list[str]) -> np.ndarray:
        return self.model.encode(texts, normalize_embeddings=True).astype("float32")


class KnowledgeBase:
    def __init__(self, kb_path: Path | None = None, backend: str | None = None):
        s = get_settings()
        kb_path = kb_path or s.kb_path
        raw = json.loads(Path(kb_path).read_text(encoding="utf-8"))
        self.entries: list[dict] = raw["entries"]
        self.items: list[KBItem] = []
        for i, e in enumerate(self.entries):
            self.items.append(KBItem(i, "statement", e["statement"]))
            for fc in e["common_false_claims"]:
                self.items.append(KBItem(i, "false_claim", fc))
        corpus = [it.text for it in self.items]
        backend = backend or s.embedding_backend
        self.embedder: TfidfEmbedder | SentenceTransformerEmbedder
        if backend == "sentence-transformers":
            try:
                self.embedder = SentenceTransformerEmbedder(s.embedding_model)
            except Exception as exc:  # noqa: BLE001
                log.warning("sentence-transformers unavailable (%s); falling back to TF-IDF embeddings", exc)
                self.embedder = TfidfEmbedder(corpus)
        else:
            self.embedder = TfidfEmbedder(corpus)
        mat = self.embedder.encode(corpus)
        self.index = faiss.IndexFlatIP(mat.shape[1])
        self.index.add(mat)
        log.info("KB ready: %d entries, %d vectors, backend=%s dim=%d", len(self.entries), len(self.items), self.embedder.name, mat.shape[1])

    # ------------------------------------------------------------------ retrieval
    def retrieve(self, claim: str, k: int = 8) -> list[dict]:
        """Top entries (deduplicated by KB entry), each with its best statement/false-claim similarity."""
        q = self.embedder.encode([claim])
        if not np.any(q):
            return []
        sims, idxs = self.index.search(q, min(k, len(self.items)))
        best: dict[int, dict] = {}
        for sim, ix in zip(sims[0], idxs[0]):
            if ix < 0:
                continue
            it = self.items[ix]
            cur = best.setdefault(it.entry_idx, {"entry_idx": it.entry_idx, "top_sim": 0.0, "top_kind": "", "top_text": ""})
            if sim > cur["top_sim"]:
                cur.update(top_sim=float(sim), top_kind=it.kind, top_text=it.text)
        return sorted(best.values(), key=lambda d: -d["top_sim"])

    def assess(self, claim: str) -> dict:
        hits = [h for h in self.retrieve(claim) if h["top_sim"] >= RELEVANT_MIN][:3]
        if not hits:
            return {"assessment": "unverified", "confidence": 0.0, "rationale":
                    "No sufficiently similar entry exists in the knowledge base, so this claim could not be checked. This is not evidence that it is true or false.",
                    "evidence": []}
        top = hits[0]
        entry = self.entries[top["entry_idx"]]
        claim_neg = negation_polarity(claim)
        item_neg = negation_polarity(top["top_text"])
        same_polarity = claim_neg == item_neg
        evidence = [self._evidence(h) for h in hits]
        sim = top["top_sim"]
        if sim < DECISIVE_MIN:
            return {"assessment": "insufficient", "confidence": round(sim, 2),
                    "rationale": f"The closest knowledge-base entry ('{entry['title']}') is only loosely related (similarity {sim:.2f}); "
                                 "it is shown for context but is not decisive.",
                    "evidence": evidence}
        agrees_with_statement = (top["top_kind"] == "statement") == same_polarity
        if agrees_with_statement:
            return {"assessment": "supported", "confidence": round(min(0.95, sim), 2),
                    "rationale": f"The claim closely matches the established finding in '{entry['title']}' (similarity {sim:.2f}).",
                    "evidence": evidence}
        return {"assessment": "contradicted", "confidence": round(min(0.95, sim), 2),
                "rationale": f"The claim matches a known false or misleading claim about '{entry['title']}' "
                             f"(similarity {sim:.2f}); the knowledge-base entry states the opposite.",
                "evidence": evidence}

    def _evidence(self, hit: dict) -> dict:
        e = self.entries[hit["entry_idx"]]
        return {
            "kb_id": e["id"], "title": e["title"], "statement": e["statement"],
            "similarity": round(hit["top_sim"], 3), "source_name": e["source_name"], "source_url": e.get("source_url"),
            "relation": "matches_statement" if hit["top_kind"] == "statement" else "matches_known_false_claim",
        }

    def info(self) -> dict:
        return {"ready": True, "kb_entries": len(self.entries), "vectors": len(self.items), "backend": self.embedder.name,
                "dimensions": int(self.embedder.dim), "index": "faiss.IndexFlatIP"}
