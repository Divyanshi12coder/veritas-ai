"""Populate the dashboard with real analyses produced by the real pipeline.

    python -m app.scripts.seed --samples            # run the bundled sample articles
    python -m app.scripts.seed --from-test 40       # analyse 40 held-out test-split articles (needs data/raw/test.parquet)

Nothing is fabricated: every row is generated by running the models on actual text.
"""
from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

from ..config import ROOT_DIR, get_settings
from ..database import SessionLocal, init_db
from ..services import analysis as svc
from ..services.registry import registry


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", action="store_true")
    ap.add_argument("--from-test", type=int, default=0, metavar="N")
    args = ap.parse_args()
    init_db()
    registry.load()
    db = SessionLocal()
    n = 0
    if args.samples:
        for s in json.loads(get_settings().samples_path.read_text(encoding="utf-8"))["samples"]:
            svc.analyze_article(db, title=s["title"], body=s["body"], author=s["author"], source_url=s["source_url"], use_llm=False)
            n += 1
    if args.from_test:
        import pandas as pd

        path = Path(ROOT_DIR / "data" / "raw" / "test.parquet")
        df = pd.read_parquet(path)
        df = df[df["text"].str.len() > 300]
        rows = df.sample(min(args.from_test, len(df)), random_state=7)
        for _, r in rows.iterrows():
            svc.analyze_article(db, title=str(r["title"])[:300] or "Untitled", body=str(r["text"])[:20000], use_llm=False)
            n += 1
    db.close()
    print(f"seeded {n} analyses")


if __name__ == "__main__":
    random.seed(0)
    main()
